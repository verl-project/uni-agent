emit_record() {
  local phase="$1"
  local kind="$2"
  local payload="$3"
  "$JSON_PYTHON" - "$phase" "$kind" "$payload" <<'PY'
import json
import sys

phase, kind, raw = sys.argv[1:]
try:
    payload = json.loads(raw)
except Exception as exc:
    sys.stderr.write("retire_node.sh: CAPE returned invalid JSON for {}: {}\n".format(phase, exc))
    raise SystemExit(2)
record = {"phase": phase, kind: payload}
sys.stdout.write(json.dumps(record, sort_keys=True) + "\n")
PY
}

resolve_node_allocation() {
  local payload="$1"
  local selected_node="$2"
  "$JSON_PYTHON" - "$selected_node" "$payload" <<'PY'
import json
import sys

node_id, raw = sys.argv[1:]
try:
    payload = json.loads(raw)
    nodes = payload["node_states"]
except Exception as exc:
    sys.stderr.write("retire_node.sh: utilization JSON has no valid node_states: {}\n".format(exc))
    raise SystemExit(2)
matches = [node for node in nodes if node.get("node_id") == node_id]
if not matches:
    sys.stderr.write("retire_node.sh: unknown node id: {}\n".format(node_id))
    raise SystemExit(2)
allocations = {node.get("allocation_id") for node in matches}
if len(matches) != 1 or len(allocations) != 1:
    sys.stderr.write("retire_node.sh: ambiguous node id in utilization: {}\n".format(node_id))
    raise SystemExit(2)
allocation = allocations.pop()
if not allocation:
    sys.stderr.write("retire_node.sh: node {} has no allocation id\n".format(node_id))
    raise SystemExit(2)
sys.stdout.write(str(allocation) + "\n")
PY
}

allocation_metrics() {
  local payload="$1"
  local selected_allocation="$2"
  "$JSON_PYTHON" - "$selected_allocation" "$payload" <<'PY'
import json
import sys

allocation_id, raw = sys.argv[1:]
try:
    payload = json.loads(raw)
    node_states = payload["node_states"]
    pool_nodes = int(payload["nodes"])
except Exception as exc:
    sys.stderr.write("retire_node.sh: utilization JSON has no valid node_states: {}\n".format(exc))
    raise SystemExit(2)
if pool_nodes != len(node_states):
    sys.stderr.write("retire_node.sh: utilization nodes count is inconsistent\n")
    raise SystemExit(2)
nodes = [node for node in node_states if node.get("allocation_id") == allocation_id]
sessions = 0
requests = 0
schedulable = 0
for node in nodes:
    for key in ("active_session_count", "nonterminal_requests"):
        if key not in node:
            sys.stderr.write(
                "retire_node.sh: utilization node {} lacks required field {}\n".format(
                    node.get("node_id", "<unknown>"), key
                )
            )
            raise SystemExit(2)
    count = int(node["active_session_count"])
    if count < 0 or ("active_sessions" in node and
                     (not isinstance(node["active_sessions"], list) or count != len(node["active_sessions"]))):
        sys.stderr.write("retire_node.sh: active session count is inconsistent\n")
        raise SystemExit(2)
    sessions += count
    requests += int(node["nonterminal_requests"])
    schedulable += int(node.get("state") == "ACTIVE")
sys.stdout.write("{} {} {} {} {}\n".format(
    len(nodes), sessions, requests, schedulable, pool_nodes
))
PY
}

read_metrics() {
  local payload="$1"
  local metrics
  metrics="$(allocation_metrics "$payload" "$allocation_id")" || exit $?
  read -r TARGET_NODES ACTIVE_SESSIONS NONTERMINAL_REQUESTS SCHEDULABLE_NODES POOL_NODES <<< "$metrics"
}

note_if_pool_became_empty() {
  if [ "$INITIAL_POOL_NODES" -eq "$INITIAL_TARGET_NODES" ] && \
     [ "$INITIAL_POOL_NODES" -gt 0 ] && \
     [ "$POOL_NODES" -eq 0 ]; then
    log "pool $CAPE_RETIRE_POOL is now empty and reconfigurable; an administrator can now change its configuration with admin pool edit"
  fi
}

run_node() {
  local phase="$1"
  shift
  local output
  output="$(cape_call node "$@")" || \
    fail "CAPE node $phase failed for allocation $allocation_id"
  emit_record "$phase" allocation "$output"
}

ensure_cape_client
before="$(query_utilization)"
emit_record before utilization "$before"

if [ -n "$node_id" ]; then
  allocation_id="$(resolve_node_allocation "$before" "$node_id")" || exit $?
  log "resolved node $node_id to allocation $allocation_id"
fi

read_metrics "$before"
INITIAL_TARGET_NODES="$TARGET_NODES"
INITIAL_POOL_NODES="$POOL_NODES"
if [ "$TARGET_NODES" -eq 0 ]; then
  log "allocation $allocation_id is already absent from visible pool capacity"
  emit_record after utilization "$before"
  [ "$strict" != 1 ] || exit 1
  exit 0
fi

log "target allocation=$allocation_id nodes=$TARGET_NODES mode=$([ "$force" = 1 ] && printf force || { [ "$drain_only" = 1 ] && printf drain-only || printf graceful; }) annotation=$reason"

mapfile -t target_node_ids < <("$JSON_PYTHON" -c 'import json,sys; print("\n".join(n["node_id"] for n in json.loads(sys.argv[1])["node_states"] if n.get("allocation_id")==sys.argv[2]))' "$before" "$allocation_id")
[ "${#target_node_ids[@]}" -gt 0 ] || fail "no matching enrolled nodes"
force_args=()
[ "$force" != 1 ] || force_args+=(--force)
for target_node_id in "${target_node_ids[@]}"; do
  run_node drain drain "$target_node_id" "${force_args[@]}"
done

if [ "$drain_only" = 1 ]; then
  after="$(query_utilization)"
  emit_record after utilization "$after"
  read_metrics "$after"
  [ "$SCHEDULABLE_NODES" -eq 0 ] || \
    fail "drain returned but allocation $allocation_id remains schedulable"
  log "allocation $allocation_id is draining; register_node.sh remains operator-owned"
  exit 0
fi

started_at="$(date +%s)"
while :; do
  current="$(query_utilization)"
  read_metrics "$current"
  emit_record wait utilization "$current"
  if [ "$TARGET_NODES" -eq 0 ]; then
    emit_record after utilization "$current"
    note_if_pool_became_empty
    log "allocation $allocation_id disappeared during graceful wait"
    exit 0
  fi
  now="$(date +%s)"
  if [ $((now - started_at)) -ge "$wait_timeout" ]; then
    emit_record after utilization "$current"
    fail "timed out after ${wait_timeout}s waiting for allocation $allocation_id: active_sessions=$ACTIVE_SESSIONS nonterminal_requests=$NONTERMINAL_REQUESTS; allocation remains drained"
  fi
  sleep "$poll_interval"
done

usage() {
  cat <<'EOF'
Credential input: --token-file FILE (private personal credential JSON).
Use an explicit controller URL and pool; controller.sh no longer generates handoffs.

Usage:
  retire_node.sh [OPTIONS] --allocation-id ALLOCATION_ID
  retire_node.sh [OPTIONS] --node-id NODE_ID

Logically retire one CAPE node allocation. The default graceful mode drains
the allocation, waits until its nodes have no active sessions or non-terminal
requests, then removes it. This script does not cancel individual requests.

Identity (exactly one required):
  --allocation-id ID      Retire this logical CAPE allocation directly
  --node-id ID            Resolve this node's allocation from utilization

Modes:
  default                 Graceful drain, bounded wait, then remove
  --drain-only            Drain and verify capacity is unschedulable; do not wait/remove
  --force                 Cancel assigned commands with `node drain --force`;
                          wait for cancellation and verified cleanup
  --strict                Treat an already-absent --allocation-id as an error

Connection and behavior:
  --controller-env FILE   Trusted controller.env generated by controller.sh
  --controller-url URL    Override the handoff controller URL
  --pool POOL             Override the handoff pool
  --token TOKEN           Override the handoff admin token
  --reason REASON         Local log annotation (default: operator_retire)
  --timeout SECONDS       Graceful wait bound (default: 300, integer)
  --poll-interval SECONDS Poll interval (default: 1, non-negative number)
  -h, --help              Show this help

Role-local client overrides:
  CAPE_RETIRE_BIN             Implementation selector (default: rscape).
                              Set pycape to use the role-local Python venv;
                              an explicit path uses that prepared executable.
  CAPE_RETIRE_REPO_ROOT       Retirement host's combined CAPE repository root
  CAPE_RETIRE_PROJECT         Retirement host's Python project directory
                              (default: RETIRE_REPO_ROOT/pycape)
  CAPE_RETIRE_VENV_ROOT       Role-local venv root (default: REPO_ROOT/venv)
  CAPE_RETIRE_VENV_HOST_ID    Host component of the default venv identity
  CAPE_RETIRE_VENV            Exact Python 3.12 venv path
  CAPE_RETIRE_PYTHON_312      Explicit Python 3.12 executable
  CAPE_RETIRE_PIXI_BIN        Explicit Pixi executable
  CAPE_RETIRE_JSON_PYTHON     Python used only for structural JSON parsing
  CAPE_FORCE_INSTALL=1        Force a CAPE reinstall

Output is JSON Lines with labelled before/drain/wait/remove/after evidence;
diagnostics go to stderr. Token values are never printed.

Retirement is logical and never signals a remote process. After successful
removal, the default register_node.sh agent learns the
authoritative removal from its heartbeat, cleans local sessions, and exits 0.
An agent started with --stay-after-removal remains alive. This script does not release
the underlying Slurm/ssh-gw allocation; manage that allocation separately.
EOF
}


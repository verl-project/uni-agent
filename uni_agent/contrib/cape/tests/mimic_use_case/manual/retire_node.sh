resolve_executable() {
  local candidate="$1"
  local label="$2"
  if [[ "$candidate" == */* ]]; then
    candidate="${candidate/#\~/$HOME}"
    [ -x "$candidate" ] || die "$label is not executable: $candidate"
    printf '%s\n' "$candidate"
  else
    command -v "$candidate" 2>/dev/null || die "$label was not found: $candidate"
  fi
}

select_json_python() {
  if [ -n "$CAPE_RETIRE_JSON_PYTHON" ]; then
    JSON_PYTHON="$(resolve_executable "$CAPE_RETIRE_JSON_PYTHON" CAPE_RETIRE_JSON_PYTHON)"
  elif [ -n "${VENV_PYTHON:-}" ] && [ -x "$VENV_PYTHON" ]; then
    JSON_PYTHON="$VENV_PYTHON"
  elif command -v python3 >/dev/null 2>&1; then
    JSON_PYTHON="$(command -v python3)"
  else
    die "structural utilization parsing requires CAPE_RETIRE_JSON_PYTHON or python3"
  fi
}

ensure_cape_client() {
  if [ "$CAPE_RETIRE_BIN_SELECTION" != pycape ]; then
    CAPE_RETIRE_BIN="$(cape_resolve_executable "$CAPE_RETIRE_BIN_SELECTION" CAPE_RETIRE_BIN)" || exit 2
    cape_inspect_executable "$CAPE_RETIRE_BIN_SELECTION" "$CAPE_RETIRE_BIN" || exit 2
    cape_record_executable retire "$CAPE_RETIRE_BIN"
    select_json_python
    return
  fi

  CAPE_RETIRE_BIN="$CAPE_RETIRE_VENV/bin/pycape"
  VENV_PYTHON="$CAPE_RETIRE_VENV/bin/python"
  if [ ! -f "$CAPE_PROJECT/pyproject.toml" ]; then
    if [ -x "$CAPE_RETIRE_BIN" ] && [ -x "$VENV_PYTHON" ] && \
       "$VENV_PYTHON" -c 'import aiohttp, pycape' >/dev/null 2>&1; then
      CAPE_RETIRE_BIN="$(cape_resolve_executable "$CAPE_RETIRE_BIN" CAPE_RETIRE_BIN)" || exit 2
      cape_inspect_executable "$CAPE_RETIRE_BIN_SELECTION" "$CAPE_RETIRE_BIN" || exit 2
      cape_record_executable retire "$CAPE_RETIRE_BIN"
      select_json_python
      return
    fi
    die "CAPE source is required to install the client: $CAPE_PROJECT/pyproject.toml"
  fi

  mkdir -p "$CAPE_RETIRE_VENV_ROOT"
  local install_lock="$CAPE_RETIRE_VENV_ROOT/.install-retire-${CAPE_RETIRE_VENV_HOST_ID}-$(uname -m)-python3.12.lock"
  if command -v flock >/dev/null 2>&1; then
    exec 9>"$install_lock"
    flock 9
  fi

  local venv_ready=0
  local venv_version=""
  if [ -x "$VENV_PYTHON" ]; then
    venv_version="$("$VENV_PYTHON" -c 'import sys; print("%d.%d" % sys.version_info[:2])' 2>/dev/null || true)"
    if [ "$venv_version" = 3.12 ] && \
       "$VENV_PYTHON" -m pip --version >/dev/null 2>&1; then
      venv_ready=1
    fi
  fi

  if [ "$venv_ready" != 1 ]; then
    local -a python312_cmd=()
    local python312_description=""
    if [ -n "$CAPE_RETIRE_PYTHON_312" ]; then
      local resolved_python
      resolved_python="$(resolve_executable "$CAPE_RETIRE_PYTHON_312" CAPE_RETIRE_PYTHON_312)"
      python312_cmd=("$resolved_python")
      python312_description="$resolved_python"
      python312_can_bootstrap_venv "${python312_cmd[@]}" || \
        die "$CAPE_RETIRE_PYTHON_312 cannot bootstrap a pip-enabled venv"
    elif command -v python3.12 >/dev/null 2>&1 && \
         python312_can_bootstrap_venv python3.12; then
      python312_cmd=("$(command -v python3.12)")
      python312_description="${python312_cmd[0]}"
    else
      if [ -z "$CAPE_RETIRE_PIXI_BIN" ]; then
        if command -v pixi >/dev/null 2>&1; then
          CAPE_RETIRE_PIXI_BIN="$(command -v pixi)"
        fi
      fi
      [ -n "$CAPE_RETIRE_PIXI_BIN" ] || \
        die "a pip-enabled Python 3.12 bootstrap and Pixi were not found; set CAPE_RETIRE_PYTHON_312 or CAPE_RETIRE_PIXI_BIN"
      CAPE_RETIRE_PIXI_BIN="$(resolve_executable "$CAPE_RETIRE_PIXI_BIN" CAPE_RETIRE_PIXI_BIN)"
      python312_cmd=("$CAPE_RETIRE_PIXI_BIN" exec --no-progress --spec "python=3.12" python)
      python312_description="Pixi ($CAPE_RETIRE_PIXI_BIN)"
      log "usable Python 3.12 venv bootstrap not found; bootstrapping it with $python312_description"
    fi

    local bootstrap_version
    bootstrap_version="$("${python312_cmd[@]}" -c 'import sys; print("%d.%d" % sys.version_info[:2])')" || \
      die "failed to start Python through $python312_description"
    [ "$bootstrap_version" = 3.12 ] || \
      die "Python bootstrap must provide 3.12, got $bootstrap_version"
    local bootstrap_mode
    bootstrap_mode="$(python312_bootstrap_mode "${python312_cmd[@]}")" || \
      die "$python312_description cannot bootstrap a pip-enabled venv"

    if [ -d "$CAPE_RETIRE_VENV" ] && [ ! -f "$CAPE_RETIRE_VENV/pyvenv.cfg" ]; then
      die "CAPE_RETIRE_VENV exists but is not a Python virtual environment: $CAPE_RETIRE_VENV"
    fi
    mkdir -p "$(dirname "$CAPE_RETIRE_VENV")"
    if [ -f "$CAPE_RETIRE_VENV/pyvenv.cfg" ]; then
      log "rebuilding incompatible Python 3.12 venv: $CAPE_RETIRE_VENV"
      create_python312_venv "$bootstrap_mode" "$CAPE_RETIRE_VENV" 1 \
        "${python312_cmd[@]}" >&2 || \
        die "failed to rebuild the retirement-client Python 3.12 venv"
    else
      log "creating Python 3.12 venv: $CAPE_RETIRE_VENV"
      create_python312_venv "$bootstrap_mode" "$CAPE_RETIRE_VENV" 0 \
        "${python312_cmd[@]}" >&2 || \
        die "failed to create the retirement-client Python 3.12 venv"
    fi
  fi

  [ -x "$VENV_PYTHON" ] || die "retirement-client venv Python is missing: $VENV_PYTHON"
  [ "$("$VENV_PYTHON" -c 'import sys; print("%d.%d" % sys.version_info[:2])')" = 3.12 ] || \
    die "retirement-client venv does not use Python 3.12"

  local install_marker="$CAPE_RETIRE_VENV/.cape-install-fingerprint"
  local install_fingerprint
  install_fingerprint="$("$VENV_PYTHON" -c '
import hashlib, os, sys
project, metadata = sys.argv[1:]
digest = hashlib.sha256()
digest.update(os.path.realpath(project).encode())
with open(metadata, "rb") as stream:
    digest.update(stream.read())
print(digest.hexdigest())
' "$CAPE_PROJECT" "$CAPE_PROJECT/pyproject.toml")"
  local install_ready=0
  if [ "$CAPE_FORCE_INSTALL" = 0 ] && [ -x "$CAPE_RETIRE_BIN" ] && [ -r "$install_marker" ]; then
    local recorded_fingerprint
    recorded_fingerprint="$(sed -n '1p' "$install_marker")"
    if [ "$recorded_fingerprint" = "$install_fingerprint" ] && \
       "$VENV_PYTHON" -c 'import aiohttp, pycape' >/dev/null 2>&1; then
      install_ready=1
    fi
  fi
  if [ "$install_ready" != 1 ]; then
    log "installing CAPE from $CAPE_PROJECT into $CAPE_RETIRE_VENV"
    "$VENV_PYTHON" -m pip install --disable-pip-version-check \
      --editable "$CAPE_PROJECT" >&2 || die "CAPE installation failed"
    "$VENV_PYTHON" -c \
      'import sys, aiohttp, pycape; assert sys.version_info[:2] == (3, 12)' || \
      die "installed CAPE or aiohttp could not be imported"
    [ -x "$CAPE_RETIRE_BIN" ] || \
      die "CAPE executable was not installed: $CAPE_RETIRE_BIN"
    local marker_tmp="$install_marker.tmp.$$"
    printf '%s\n' "$install_fingerprint" > "$marker_tmp"
    mv -- "$marker_tmp" "$install_marker"
  fi
  if command -v flock >/dev/null 2>&1; then
    flock -u 9
    exec 9>&-
  fi
  CAPE_RETIRE_BIN="$(cape_resolve_executable "$CAPE_RETIRE_BIN" CAPE_RETIRE_BIN)" || exit 2
  cape_inspect_executable "$CAPE_RETIRE_BIN_SELECTION" "$CAPE_RETIRE_BIN" || exit 2
  cape_record_executable retire "$CAPE_RETIRE_BIN"
  select_json_python
}

cape_call() {
  local -a args=("$@" --controller-url "$CAPE_RETIRE_URL")
  if [ -n "$CAPE_MANUAL_TOKEN_FILE" ]; then
    args+=(--token-file "$CAPE_MANUAL_TOKEN_FILE")
  else
    args+=(--token "$CAPE_RETIRE_TOKEN")
  fi
  "$CAPE_RETIRE_BIN" "${args[@]}"
}


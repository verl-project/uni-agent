usage() {
  cat <<'EOF'
Credential input: --token-file FILE (private personal credential JSON).
Use an explicit controller URL and pool; controller.sh no longer generates handoffs.

Usage:
  status.sh [OPTIONS] health
  status.sh [OPTIONS] status REQUEST_ID
  status.sh [OPTIONS] logs REQUEST_ID
  status.sh [OPTIONS] wait REQUEST_ID [--timeout SECONDS]
  status.sh [OPTIONS] utilization
  status.sh [OPTIONS] info
  status.sh [OPTIONS] controller-log [--lines N] [--follow]
  status.sh [OPTIONS] node-log [NODE_ID|all] [--lines N] [--follow]
  status.sh [OPTIONS] command-log COMMAND_ID [NODE_ID|all] [--lines N] [--follow]
  status.sh [OPTIONS] session-log SESSION_ID [NODE_ID|all] [--lines N] [--follow]

Read-only commands:
  health          Probe CONTROLLER_URL/health; no token or CAPE install needed
  status          Print one request's JSON status
  logs            Print one request's captured stdout/stderr
  wait            Wait for one request and print its terminal/timeout status
  utilization     Print JSON utilization for the configured pool
  info            Print resolved non-secret client configuration
  controller-log  Tail the controller log visible on this filesystem
  node-log        Tail one or all node-agent logs visible in STATUS_BUNDLE/pool
  command-log     Tail the exact-runtime argv/env/output log for one cmd-... id
  session-log     Tail the runtime teardown/lifecycle log for one sess-... id

Readiness interpretation:
  utilization includes active_nodes, registering_nodes, schedulable capacity,
  node_states with each node id/state/GPU count, and the established
  pool_config even when the pool is empty. REGISTERING/node_probing and
  QUEUED/pool_empty are waiting states, not failures. Before treating a request
  as stuck, confirm the expected active_nodes and schedulable GPU capacity are
  present and stable across at least one heartbeat interval.

Request timestamp interpretation:
  status and wait JSON include created_at, leased_at, started_at, ended_at, and
  updated_at. leased_at is null until placement grants a lease; started_at is
  null until RUNNING and is retained after termination; ended_at
  is set at the terminal transition. A never-run cancellation/failure keeps
  started_at null. updated_at retains latest-transition compatibility.

Options (place before the command):
  --controller-env FILE  Optional controller.env generated by controller.sh
  --controller-url URL   Override CAPE_URL from the environment file
  --token TOKEN          Override the default admin token
  --no-token             Query without authentication, overriding handoff tokens
  --pool POOL            Override CAPE_POOL
  -h, --help             Show this help

Environment equivalents:
  CAPE_CONTROLLER_ENV    Optional controller.env path
  CAPE_STATUS_URL        Controller URL override
  CAPE_STATUS_TOKEN      Query token override
  CAPE_STATUS_NO_TOKEN   Set to 1 to query without authentication
  CAPE_STATUS_POOL       Pool override
  CAPE_STATUS_BIN        Implementation selector (default: rscape).
                         Set pycape to use the role-local Python venv;
                         an explicit path uses that prepared executable.
  CAPE_STATUS_REPO_ROOT  Query host's combined CAPE repository root
  CAPE_STATUS_PROJECT    Query host's Python project directory
                         (default: STATUS_REPO_ROOT/pycape)
  CAPE_STATUS_BUNDLE     Query-host-local evidence/log bundle
  CAPE_STATUS_CONTROLLER_LOG  Explicit locally visible controller log
  CAPE_STATUS_NODE_LOG   Explicit locally visible node log
  CAPE_STATUS_AGENT_LOG_DIR
                         Explicit locally visible per-command/session log directory
  CAPE_STATUS_VENV_ROOT  Role-local venv root (default: REPO_ROOT/venv)
  CAPE_STATUS_VENV_HOST_ID
                         Host component of the default venv identity
  CAPE_STATUS_VENV       Exact status-client venv path
  CAPE_STATUS_PYTHON_312 Optional explicit Python 3.12 executable
  CAPE_STATUS_PIXI_BIN   Optional Pixi executable for Python bootstrap
  CAPE_FORCE_INSTALL     Set to 1 to reinstall CAPE (default: 0)

Queries are not tied to the controller's working directory: copy the protected
controller.env to the query host, pass its path explicitly, or set URL/token/
pool directly. Source, installation, bundle, and log paths are always resolved
on the query host through CAPE_STATUS_* values. Treat controller.env as a
credential file and keep it mode 0600.

This script is deliberately read-only. It never exposes controller start,
node enroll, run, cancel, or mutating administrator operations.
EOF
}

die() {
  printf 'status.sh: %s\n' "$*" >&2
  exit 2
}

python312_has_ensurepip_wheel() {
  "$@" -c '
import ensurepip
import pathlib
import sys
import venv

assert sys.version_info[:2] == (3, 12)
roots = [pathlib.Path(ensurepip.__file__).resolve().parent / "_bundled"]
wheel_dir = getattr(ensurepip, "_WHEEL_PKG_DIR", "")
if wheel_dir:
    roots.append(pathlib.Path(wheel_dir))
assert any(root.is_dir() and any(root.glob("pip-*.whl")) for root in roots)
' >/dev/null 2>&1
}

python312_bootstrap_mode() {
  if python312_has_ensurepip_wheel "$@"; then
    printf 'ensurepip\n'
  elif "$@" -m pip --help 2>/dev/null | grep -q -- '--python'; then
    printf 'external-pip\n'
  else
    return 1
  fi
}

python312_can_bootstrap_venv() {
  python312_bootstrap_mode "$@" >/dev/null
}

create_python312_venv() {
  local mode="$1"
  local target="$2"
  local clear_existing="$3"
  shift 3
  local -a venv_args=(-m venv --copies)
  [ "$clear_existing" != 1 ] || venv_args+=(--clear)
  [ "$mode" != external-pip ] || venv_args+=(--without-pip)
  venv_args+=("$target")
  "$@" "${venv_args[@]}" || return
  if [ "$mode" = external-pip ]; then
    "$@" -m pip --python "$target/bin/python" install \
      --disable-pip-version-check pip
  fi
}

log() {
  printf '[status] %s\n' "$*" >&2
}

require_value() {
  [ "$#" -ge 2 ] && [ -n "$2" ] || die "$1 requires a value"
}

load_controller_environment() {
  local path="$1"
  local assignments
  local local_name
  local -a portable_names=(
    CAPE_CONTROLLER_ENV_VERSION RUN_ID CASE CAPE_POOL CAPE_PORT
    CONTROLLER_HOST CAPE_URL CAPE_CONTROLLER_URL CAPE_ADMIN_TOKEN
    CAPE_JOIN_TOKEN CAPE_PROBE_NODE_TOKEN CAPE_USER_TOKENS_INLINE
  )
  assignments="$({
    set -euo pipefail
    for local_name in "${portable_names[@]}"; do unset "$local_name"; done
    # shellcheck disable=SC1090
    source "$path" >/dev/null
    for local_name in "${portable_names[@]}"; do
      if [[ -v "$local_name" ]]; then
        printf 'export %s=%q\n' "$local_name" "${!local_name}"
      fi
    done
  })" || die "failed to load controller environment: $path"
  for local_name in "${portable_names[@]}"; do unset "$local_name"; done
  eval "$assignments"
  case "${CAPE_CONTROLLER_ENV_VERSION:-missing}" in
    3) ;;
    *) die "unsupported CAPE_CONTROLLER_ENV_VERSION: ${CAPE_CONTROLLER_ENV_VERSION:-missing}; regenerate the handoff with current controller.sh" ;;
  esac
}

controller_env="${CAPE_CONTROLLER_ENV:-}"
controller_url_override=""
token_override=""
token_override_set=0
no_token="${CAPE_STATUS_NO_TOKEN:-0}"
pool_override=""
command_name=""

while [ "$#" -gt 0 ]; do
  case "$1" in
    --controller-env)
      require_value "$@"
      controller_env="$2"
      shift 2
      ;;
    --controller-env=*)
      controller_env="${1#*=}"
      [ -n "$controller_env" ] || die "--controller-env requires a value"
      shift
      ;;
    --controller-url)
      require_value "$@"
      controller_url_override="$2"
      shift 2
      ;;
    --controller-url=*)
      controller_url_override="${1#*=}"
      [ -n "$controller_url_override" ] || die "--controller-url requires a value"
      shift
      ;;
    --token)
      require_value "$@"
      token_override="$2"
      token_override_set=1
      shift 2
      ;;
    --token=*)
      token_override="${1#*=}"
      [ -n "$token_override" ] || die "--token requires a value"
      token_override_set=1
      shift
      ;;
    --no-token)
      no_token=1
      shift
      ;;
    --pool)
      require_value "$@"
      pool_override="$2"
      shift 2
      ;;
    --pool=*)
      pool_override="${1#*=}"
      [ -n "$pool_override" ] || die "--pool requires a value"
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    --)
      shift
      break
      ;;
    health|status|logs|wait|utilization|info|controller-log|node-log|command-log|session-log)
      command_name="$1"
      shift
      break
      ;;
    run|submit|node|join|controller|start|cancel|admin)
      die "'$1' is not available: status.sh permits read-only inspection only"
      ;;
    -* )
      die "unknown option: $1"
      ;;
    *)
      die "unknown read-only command: $1 (use --help)"
      ;;
  esac
done

[ -n "$command_name" ] || {
  usage >&2
  die "a read-only command is required"
}
[ "$no_token" = 0 ] || [ "$no_token" = 1 ] || \
  die "CAPE_STATUS_NO_TOKEN must be 0 or 1"
[ "$no_token" != 1 ] || [ "$token_override_set" != 1 ] || \
  die "--token and --no-token are mutually exclusive"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [ -n "$controller_env" ]; then
  case "$controller_env" in
    /*) ;;
    *) controller_env="$PWD/${controller_env#./}" ;;
  esac
  [ -r "$controller_env" ] || \
    die "controller environment is not readable: $controller_env"
  # Evaluate only a trusted handoff, then import its portable allowlist. Query
  # installation, executable, venv, bundle, and logs remain status-host-local.
  load_controller_environment "$controller_env"
fi

# Version-2 controller.env files are path-free. Ignore generic machine-local
# paths from legacy files too: status may run on another architecture or mount
# layout, so derive every installation/log path from status-specific settings.
source "$SCRIPT_DIR/../project_root.sh"
SCRIPT_REPO_ROOT="$(cape_project_root "$SCRIPT_DIR")"
REPO_ROOT="${CAPE_STATUS_REPO_ROOT:-$SCRIPT_REPO_ROOT}"
CAPE_PROJECT="${CAPE_STATUS_PROJECT:-$REPO_ROOT/pycape}"
CAPE_STATUS_URL="${controller_url_override:-${CAPE_STATUS_URL:-${CAPE_URL:-${CAPE_CONTROLLER_URL:-}}}}"
CAPE_STATUS_TOKEN="${token_override:-${CAPE_STATUS_TOKEN:-${CAPE_TOKEN:-${CAPE_ADMIN_TOKEN:-}}}}"
[ "$no_token" != 1 ] || CAPE_STATUS_TOKEN=""
CAPE_STATUS_POOL="${pool_override:-${CAPE_STATUS_POOL:-${CAPE_POOL:-}}}"
CAPE_STATUS_BUNDLE="${CAPE_STATUS_BUNDLE:-}"
CAPE_STATUS_CONTROLLER_LOG="${CAPE_STATUS_CONTROLLER_LOG:-}"
CAPE_STATUS_AGENT_LOG_DIR="${CAPE_STATUS_AGENT_LOG_DIR:-}"
CAPE_FORCE_INSTALL="${CAPE_FORCE_INSTALL:-0}"
CAPE_STATUS_VENV_ROOT="${CAPE_STATUS_VENV_ROOT:-$REPO_ROOT/venv}"
CAPE_STATUS_VENV_HOST_ID="${CAPE_STATUS_VENV_HOST_ID:-$(hostname -s 2>/dev/null || hostname)}"
CAPE_STATUS_VENV_HOST_ID="${CAPE_STATUS_VENV_HOST_ID//[^A-Za-z0-9_.-]/_}"
CAPE_STATUS_VENV="${CAPE_STATUS_VENV:-${CAPE_STATUS_VENV_ROOT}/status-${CAPE_STATUS_VENV_HOST_ID}-$(uname -m)-python3.12}"
CAPE_STATUS_BIN_SELECTION="${CAPE_STATUS_BIN:-rscape}"
CAPE_STATUS_PYTHON_312="${CAPE_STATUS_PYTHON_312:-}"
CAPE_STATUS_PIXI_BIN="${CAPE_STATUS_PIXI_BIN:-}"

if [ -n "$CAPE_STATUS_BUNDLE" ]; then
  case "$CAPE_STATUS_BUNDLE" in
    /*) ;;
    *) CAPE_STATUS_BUNDLE="$PWD/${CAPE_STATUS_BUNDLE#./}" ;;
  esac
fi
if [ -z "$CAPE_STATUS_CONTROLLER_LOG" ] && [ -n "$CAPE_STATUS_BUNDLE" ]; then
  CAPE_STATUS_CONTROLLER_LOG="$CAPE_STATUS_BUNDLE/pool/controller/controller.log"
fi
if [ -n "$CAPE_STATUS_AGENT_LOG_DIR" ]; then
  case "$CAPE_STATUS_AGENT_LOG_DIR" in
    /*) ;;
    *) CAPE_STATUS_AGENT_LOG_DIR="$PWD/${CAPE_STATUS_AGENT_LOG_DIR#./}" ;;
  esac
fi

case "$CAPE_FORCE_INSTALL" in
  0|1) ;;
  *) die "CAPE_FORCE_INSTALL must be 0 or 1" ;;
esac
case "$CAPE_STATUS_VENV" in
  /*) ;;
  *) CAPE_STATUS_VENV="$PWD/${CAPE_STATUS_VENV#./}" ;;
esac
case "$CAPE_STATUS_VENV_ROOT" in
  /*) ;;
  *) CAPE_STATUS_VENV_ROOT="$PWD/${CAPE_STATUS_VENV_ROOT#./}" ;;
esac
if [ -n "$CAPE_STATUS_URL" ]; then
  case "$CAPE_STATUS_URL" in
    http://*|https://*) ;;
    *) die "controller URL must begin with http:// or https://: $CAPE_STATUS_URL" ;;
  esac
  CAPE_STATUS_URL="${CAPE_STATUS_URL%/}"
fi

require_controller_url() {
  [ -n "$CAPE_STATUS_URL" ] || \
    die "controller URL is required; pass --controller-env, --controller-url, or CAPE_STATUS_URL"
}

require_pool() {
  [ -n "$CAPE_STATUS_POOL" ] || \
    die "pool is required; pass --pool, --controller-env, or CAPE_STATUS_POOL"
}

resolve_executable() {
  local candidate="$1"
  local label="$2"
  if [[ "$candidate" == */* ]]; then
    candidate="${candidate/#\~/$HOME}"
    [ -x "$candidate" ] || die "$label is not executable: $candidate"
    printf '%s\n' "$candidate"
  else
    command -v "$candidate" 2>/dev/null || die "$label was not found: $candidate"
  fi
}

ensure_cape_client() {
  local evidence_file=""
  [ -z "$CAPE_STATUS_BUNDLE" ] || \
    evidence_file="$CAPE_STATUS_BUNDLE/status-client-implementation.txt"
  if [ "$CAPE_STATUS_BIN_SELECTION" != pycape ]; then
    CAPE_STATUS_BIN="$(cape_resolve_executable "$CAPE_STATUS_BIN_SELECTION" CAPE_STATUS_BIN)" || exit 2
    cape_inspect_executable "$CAPE_STATUS_BIN_SELECTION" "$CAPE_STATUS_BIN" || exit 2
    cape_record_executable status "$CAPE_STATUS_BIN" "$evidence_file"
    return
  fi

  CAPE_STATUS_BIN="$CAPE_STATUS_VENV/bin/pycape"
  VENV_PYTHON="$CAPE_STATUS_VENV/bin/python"

  if [ ! -f "$CAPE_PROJECT/pyproject.toml" ]; then
    if [ -x "$CAPE_STATUS_BIN" ] && [ -x "$VENV_PYTHON" ] && \
       "$VENV_PYTHON" -c 'import aiohttp, pycape' >/dev/null 2>&1; then
      CAPE_STATUS_BIN="$(cape_resolve_executable "$CAPE_STATUS_BIN" CAPE_STATUS_BIN)" || exit 2
      cape_inspect_executable "$CAPE_STATUS_BIN_SELECTION" "$CAPE_STATUS_BIN" || exit 2
      cape_record_executable status "$CAPE_STATUS_BIN" "$evidence_file"
      return
    fi
    die "CAPE source is required to install the client: $CAPE_PROJECT/pyproject.toml"
  fi

  mkdir -p "$CAPE_STATUS_VENV_ROOT"
  local install_lock="$CAPE_STATUS_VENV_ROOT/.install-status-${CAPE_STATUS_VENV_HOST_ID}-$(uname -m)-python3.12.lock"
  if command -v flock >/dev/null 2>&1; then
    exec 9>"$install_lock"
    flock 9
  fi

  local venv_ready=0
  local venv_version=""
  if [ -x "$VENV_PYTHON" ]; then
    venv_version="$($VENV_PYTHON -c 'import sys; print("%d.%d" % sys.version_info[:2])' 2>/dev/null || true)"
    if [ "$venv_version" = 3.12 ] && \
       "$VENV_PYTHON" -m pip --version >/dev/null 2>&1; then
      venv_ready=1
    fi
  fi

  if [ "$venv_ready" != 1 ]; then
    local -a python312_cmd=()
    local python312_description=""

    if [ -n "$CAPE_STATUS_PYTHON_312" ]; then
      local resolved_python
      resolved_python="$(resolve_executable "$CAPE_STATUS_PYTHON_312" CAPE_STATUS_PYTHON_312)"
      python312_cmd=("$resolved_python")
      python312_description="$resolved_python"
      python312_can_bootstrap_venv "${python312_cmd[@]}" || \
        die "$CAPE_STATUS_PYTHON_312 cannot bootstrap a pip-enabled venv"
    elif command -v python3.12 >/dev/null 2>&1 && \
         python312_can_bootstrap_venv python3.12; then
      python312_cmd=("$(command -v python3.12)")
      python312_description="${python312_cmd[0]}"
    else
      if [ -z "$CAPE_STATUS_PIXI_BIN" ]; then
        if command -v pixi >/dev/null 2>&1; then
          CAPE_STATUS_PIXI_BIN="$(command -v pixi)"
        fi
      fi
      [ -n "$CAPE_STATUS_PIXI_BIN" ] || \
        die "a pip-enabled Python 3.12 bootstrap and Pixi were not found; set CAPE_STATUS_PYTHON_312 or CAPE_STATUS_PIXI_BIN"
      CAPE_STATUS_PIXI_BIN="$(resolve_executable "$CAPE_STATUS_PIXI_BIN" CAPE_STATUS_PIXI_BIN)"
      python312_cmd=("$CAPE_STATUS_PIXI_BIN" exec --no-progress --spec "python=3.12" python)
      python312_description="Pixi ($CAPE_STATUS_PIXI_BIN)"
      log "usable Python 3.12 venv bootstrap not found; bootstrapping it with $python312_description"
    fi

    local bootstrap_version
    bootstrap_version="$("${python312_cmd[@]}" -c 'import sys; print("%d.%d" % sys.version_info[:2])')" || \
      die "failed to start Python through $python312_description"
    [ "$bootstrap_version" = 3.12 ] || \
      die "Python bootstrap must provide 3.12, got $bootstrap_version"
    local python312_bootstrap_mode
    python312_bootstrap_mode="$(python312_bootstrap_mode "${python312_cmd[@]}")" || \
      die "$python312_description cannot bootstrap a pip-enabled venv"

    if [ -d "$CAPE_STATUS_VENV" ] && [ ! -f "$CAPE_STATUS_VENV/pyvenv.cfg" ]; then
      die "CAPE_STATUS_VENV exists but is not a Python virtual environment: $CAPE_STATUS_VENV"
    fi
    mkdir -p "$(dirname "$CAPE_STATUS_VENV")"
    if [ -f "$CAPE_STATUS_VENV/pyvenv.cfg" ]; then
      log "rebuilding incompatible Python 3.12 venv: $CAPE_STATUS_VENV"
      create_python312_venv "$python312_bootstrap_mode" "$CAPE_STATUS_VENV" 1 \
        "${python312_cmd[@]}" >&2 || \
        die "failed to rebuild the status-client Python 3.12 venv"
    else
      log "creating Python 3.12 venv: $CAPE_STATUS_VENV"
      create_python312_venv "$python312_bootstrap_mode" "$CAPE_STATUS_VENV" 0 \
        "${python312_cmd[@]}" >&2 || \
        die "failed to create the status-client Python 3.12 venv"
    fi
  fi

  [ -x "$VENV_PYTHON" ] || die "status-client venv Python is missing: $VENV_PYTHON"
  [ "$($VENV_PYTHON -c 'import sys; print("%d.%d" % sys.version_info[:2])')" = 3.12 ] || \
    die "status-client venv does not use Python 3.12"

  local install_marker="$CAPE_STATUS_VENV/.cape-install-fingerprint"
  local install_fingerprint
  install_fingerprint="$($VENV_PYTHON -c '
import hashlib, os, sys
project, metadata = sys.argv[1:]
digest = hashlib.sha256()
digest.update(os.path.realpath(project).encode())
with open(metadata, "rb") as stream:
    digest.update(stream.read())
print(digest.hexdigest())
' "$CAPE_PROJECT" "$CAPE_PROJECT/pyproject.toml")"

  local install_ready=0
  if [ "$CAPE_FORCE_INSTALL" = 0 ] && [ -x "$CAPE_STATUS_BIN" ] && [ -r "$install_marker" ]; then
    local recorded_fingerprint
    recorded_fingerprint="$(sed -n '1p' "$install_marker")"
    if [ "$recorded_fingerprint" = "$install_fingerprint" ] && \
       "$VENV_PYTHON" -c 'import aiohttp, pycape' >/dev/null 2>&1; then
      install_ready=1
    fi
  fi

  if [ "$install_ready" != 1 ]; then
    log "installing CAPE from $CAPE_PROJECT into $CAPE_STATUS_VENV"
    "$VENV_PYTHON" -m pip install \
      --disable-pip-version-check \
      --editable "$CAPE_PROJECT" >&2 || die "CAPE installation failed"
    "$VENV_PYTHON" -c \
      'import sys, aiohttp, pycape; assert sys.version_info[:2] == (3, 12)' || \
      die "installed CAPE or aiohttp could not be imported"
    [ -x "$CAPE_STATUS_BIN" ] || \
      die "CAPE executable was not installed: $CAPE_STATUS_BIN"
    local marker_tmp="$install_marker.tmp.$$"
    printf '%s\n' "$install_fingerprint" > "$marker_tmp"
    mv -- "$marker_tmp" "$install_marker"
  fi

  if command -v flock >/dev/null 2>&1; then
    flock -u 9
    exec 9>&-
  fi
  CAPE_STATUS_BIN="$(cape_resolve_executable "$CAPE_STATUS_BIN" CAPE_STATUS_BIN)" || exit 2
  cape_inspect_executable "$CAPE_STATUS_BIN_SELECTION" "$CAPE_STATUS_BIN" || exit 2
  cape_record_executable status "$CAPE_STATUS_BIN" "$evidence_file"
}

cape_query() {
  local query_command="$1"
  shift
  require_controller_url
  ensure_cape_client
  local -a query_args=("$query_command" "$@" --controller-url "$CAPE_STATUS_URL")
  if [ -n "$CAPE_MANUAL_TOKEN_FILE" ]; then
    query_args+=(--token-file "$CAPE_MANUAL_TOKEN_FILE")
  else
    [ -z "$CAPE_STATUS_TOKEN" ] || query_args+=(--token "$CAPE_STATUS_TOKEN")
  fi
  exec "$CAPE_STATUS_BIN" "${query_args[@]}"
}

parse_tail_options() {
  TAIL_LINES="${CAPE_STATUS_LOG_LINES:-80}"
  TAIL_FOLLOW=0
  while [ "$#" -gt 0 ]; do
    case "$1" in
      --lines)
        require_value "$@"
        TAIL_LINES="$2"
        shift 2
        ;;
      --lines=*)
        TAIL_LINES="${1#*=}"
        shift
        ;;
      -f|--follow)
        TAIL_FOLLOW=1
        shift
        ;;
      *)
        die "unexpected log option: $1"
        ;;
    esac
  done
  case "$TAIL_LINES" in
    ''|*[!0-9]*) die "--lines must be a non-negative integer" ;;
  esac
}

tail_logs() {
  local -a files=("${!1}")
  [ "${#files[@]}" -gt 0 ] || die "no matching log files were found"
  local -a tail_args=(-n "$TAIL_LINES")
  [ "$TAIL_FOLLOW" != 1 ] || tail_args=(-F -n "$TAIL_LINES")
  exec tail "${tail_args[@]}" -- "${files[@]}"
}

tail_agent_detail_log() {
  local kind="$1"
  local log_id="$2"
  shift 2
  local prefix
  local node_selector=all
  local suffix
  case "$kind" in
    command) prefix=cmd- ;;
    session) prefix=sess- ;;
    *) die "internal unsupported agent-log kind: $kind" ;;
  esac
  case "$log_id" in
    "$prefix"*) ;;
    *) die "$kind log id must begin with $prefix" ;;
  esac
  suffix="${log_id#"$prefix"}"
  case "$suffix" in
    ''|*[!A-Za-z0-9_.-]*) die "$kind log id contains unsupported characters: $log_id" ;;
  esac
  if [ "$#" -gt 0 ] && [[ "$1" != -* ]]; then
    node_selector="$1"
    shift
  fi
  case "$node_selector" in
    all) ;;
    ''|*[!A-Za-z0-9_.-]*) die "NODE_ID contains unsupported characters: $node_selector" ;;
  esac
  parse_tail_options "$@"

  local -a detail_logs=()
  if [ -n "$CAPE_STATUS_AGENT_LOG_DIR" ]; then
    [ "$node_selector" = all ] || \
      die "NODE_ID cannot be combined with CAPE_STATUS_AGENT_LOG_DIR"
    [ -r "$CAPE_STATUS_AGENT_LOG_DIR/$log_id.log" ] || \
      die "$kind log is not readable: $CAPE_STATUS_AGENT_LOG_DIR/$log_id.log"
    detail_logs+=("$CAPE_STATUS_AGENT_LOG_DIR/$log_id.log")
  elif [ -n "$CAPE_STATUS_BUNDLE" ]; then
    if [ "$node_selector" = all ]; then
      shopt -s nullglob
      detail_logs=("$CAPE_STATUS_BUNDLE"/pool/*/agent-logs/"$log_id.log")
      shopt -u nullglob
    else
      [ -r "$CAPE_STATUS_BUNDLE/pool/$node_selector/agent-logs/$log_id.log" ] || \
        die "$kind log is not readable for node $node_selector: $log_id"
      detail_logs+=("$CAPE_STATUS_BUNDLE/pool/$node_selector/agent-logs/$log_id.log")
    fi
  else
    die "$kind log path is unavailable; set CAPE_STATUS_AGENT_LOG_DIR or CAPE_STATUS_BUNDLE"
  fi
  tail_logs 'detail_logs[@]'
}


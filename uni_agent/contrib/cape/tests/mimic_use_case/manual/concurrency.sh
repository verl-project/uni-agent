        gpu_row_counts[gpu_name] = tid
        row_name = "{} ({})".format(row["label"] or "workload", request_id)
        trace_events.append({"ph": "M", "pid": pid, "tid": tid,
                             "name": "thread_name",
                             "args": {"name": row_name}})
        trace_events.append({"ph": "M", "pid": pid, "tid": tid,
                             "name": "thread_sort_index",
                             "args": {"sort_index": tid}})
        # Compute every boundary exactly once, rounded to WHOLE microseconds,
        # and share it between adjacent slices. Two invariants matter:
        # 1) a slice's end and its successor's start must be identical, or
        #    Perfetto sees a partial overlap and shunts the slice onto an
        #    ambiguous overflow track (so the ledger's 3-decimal
        #    submit_offset must not be used as a boundary); and
        # 2) ts and dur must survive Perfetto's independent round(x*1000)
        #    nanosecond conversion without drifting — fractional
        #    microseconds can round ts and dur differently and reintroduce
        #    a 1 ns overlap, so boundaries are integers and durations are
        #    integer differences.
        submit_us = round(micros_from_t0(submit_time))
        candidate_slices = []
        if row["scheduled_offset"] is not None:
            scheduled_us = round(row["scheduled_offset"] * 1e6)
            if submit_us > scheduled_us:
                candidate_slices.append(("submit-wait", scheduled_us, submit_us))
        if work_start is not None and work_end is not None:
            work_start_us = round(micros_from_t0(work_start))
            work_end_us = round(micros_from_t0(work_end))
            if work_start_us > submit_us:
                candidate_slices.append(("queuing", submit_us, work_start_us))
            complete_phases = (
                cpu_done is not None
                and gpu_done is not None
                and work_start <= cpu_done <= gpu_done <= work_end
            )
            if complete_phases:
                cpu_done_us = round(micros_from_t0(cpu_done))
                gpu_done_us = round(micros_from_t0(gpu_done))
                if cpu_done_us > work_start_us:
                    candidate_slices.append((
                        "processing:cpu", work_start_us, cpu_done_us,
                    ))
                if row["lock_wait_time"] is not None:
                    lock_start_us = round(micros_from_t0(record["lock_wait_start"]))
                    lock_acquired_us = round(micros_from_t0(record["lock_acquired"]))
                    for name, start, end in (
                        ("processing:prepare", cpu_done_us, lock_start_us),
                        ("processing:lock-wait", lock_start_us, lock_acquired_us),
                        ("processing:gpu", lock_acquired_us, gpu_done_us),
                    ):
                        if end > start:
                            candidate_slices.append((name, start, end))
                elif gpu_done_us > cpu_done_us:
                    candidate_slices.append((
                        "processing:gpu", cpu_done_us, gpu_done_us,
                    ))
                if work_end_us > gpu_done_us:
                    candidate_slices.append((
                        "processing:finish", gpu_done_us, work_end_us,
                    ))
            elif work_end_us > work_start_us:
                candidate_slices.append((
                    "processing", work_start_us, work_end_us,
                ))
        elif terminal_time is not None:
            terminal_us = round(micros_from_t0(terminal_time))
            if terminal_us > submit_us:
                candidate_slices.append((
                    "request (fallback: submit->terminal)",
                    submit_us, terminal_us,
                ))
        cursor = None
        for slice_name, start_us, end_us in candidate_slices:
            if cursor is not None and start_us < cursor:
                # A genuinely overlapping interval (e.g. cross-clock skew put
                # work_start before submit). The report already flags it as
                # an anomaly; drawing it would be ambiguous, so skip it.
                continue
            event_args = dict(slice_args)
            event_args["phase"] = slice_name
            trace_events.append({
                "ph": "X", "pid": pid, "tid": tid, "name": slice_name,
                "ts": start_us, "dur": end_us - start_us,
                "args": event_args,
            })
            cursor = end_us

with open(report_path + ".trace.json", "w", encoding="utf-8") as stream:
    json.dump({
        "traceEvents": trace_events,
        "displayTimeUnit": "ms",
        "otherData": {"run_id": run_id, "t0_epoch_seconds": "{:.9f}".format(t0)},
    }, stream, indent=1)
    stream.write("\n")
PYREPORT
    then
      log "warning: report generation failed"
    else
      log "report written: $report_file (+ .json, .meta.json, .trace.json for ui.perfetto.dev)"
    fi
  else

DRAWN_DELAY=""
draw_arrival_delay() {
  local random_value="$RANDOM"
  DRAWN_DELAY="$(awk \
    -v low="$arrival_min" \
    -v high="$arrival_max" \
    -v random_value="$random_value" \
    -v mode="$arrival_distribution" '
BEGIN {
  span = high - low
  if (span <= 0) {
    delay = low
  } else if (mode == "poisson") {
    u = (random_value + 1) / 32769
    extra = -log(1 - u) * (span / 3)
    if (extra > span) extra = span
    delay = low + extra
  } else {
    delay = low + span * (random_value / 32767)
  }
  printf "%.3f", delay
}')"
}


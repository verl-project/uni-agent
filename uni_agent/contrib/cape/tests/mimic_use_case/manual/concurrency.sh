sleep_until_offset() {
  local target_offset="$1"
  local now elapsed_since_t0 wait_seconds
  now="$(date +%s.%N)"
  elapsed_since_t0="$(awk -v now="$now" -v t0="$t0_epoch" \
    'BEGIN {printf "%.3f", now - t0}')"
  wait_seconds="$(awk -v target="$target_offset" -v elapsed="$elapsed_since_t0" \
    'BEGIN {value = target - elapsed; if (value < 0) value = 0; printf "%.3f", value}')"
  sleep_before_arrival "$wait_seconds"
}


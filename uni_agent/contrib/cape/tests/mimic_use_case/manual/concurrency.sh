# Resolve a status token for USER from the submit-host CSV or the inline map.
resolve_token_for_user() {
  local lookup_user="$1"
  RESOLVED_TOKEN=""
  [ -n "$lookup_user" ] || return 0
  if [ -n "$submit_user_tokens" ] && [ -r "$submit_user_tokens" ]; then
    RESOLVED_TOKEN="$(awk -F, -v user="$lookup_user" '
$1 == user {print $2; found=1; exit}
END {if (!found) exit 1}
' "$submit_user_tokens" 2>/dev/null || true)"
    RESOLVED_TOKEN="${RESOLVED_TOKEN%$'\r'}"
    [ -z "$RESOLVED_TOKEN" ] || return 0
  fi
  if [ -n "$submit_user_tokens_inline" ]; then
    local token_record token_user
    while IFS= read -r token_record; do
      token_user="${token_record%%,*}"
      [ "$token_user" != "$token_record" ] || continue
      [ "$token_user" = "$lookup_user" ] || continue
      RESOLVED_TOKEN="${token_record#*,}"
      RESOLVED_TOKEN="${RESOLVED_TOKEN%$'\r'}"
      break
    done <<< "$submit_user_tokens_inline"
  fi
}


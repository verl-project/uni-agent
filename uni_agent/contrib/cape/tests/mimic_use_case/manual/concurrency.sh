usage() {
  cat <<'EOF'
Credential input: --token-file FILE (private personal credential JSON).
Use an explicit controller URL and pool; controller.sh no longer generates handoffs.

Usage:
  concurrency.sh OPTIONS -- SUBMIT_OPTIONS [-- COMMAND [ARG ...]]

Example:
  concurrency.sh \
    --workloads 20 \
    --concurrency 4 \
    --arrival-window 0.5:3.0 \
    --arrival-distribution uniform \
    -- \
    --controller-env /path/to/controller.env \
    --user user-000 \
    --gpus 1 \
    --bind /shared/work:/workspace:rw \
    --cwd /workspace \
    -- python train.py

Everything after the first `--` is forwarded to submit.sh. A generic workload
therefore normally contains a second `--` before its command. A mimic request
can instead end with `--mimic A` or `--mimic B`.

Every request receives CAPE_CONCURRENCY_INDEX, CAPE_CONCURRENCY_TOTAL, and
CAPE_CONCURRENCY_RUN_ID in its workload environment, plus a unique
LABEL_PREFIX-NNNNNN submission label. Unless the forwarded submit options
already contain --session-id, every request also receives the unique session
key RUN_ID-NNNNNN so active-session reuse does not serialize a concurrency
run. Forward one explicit --session-id to request intentional reuse. Generic
commands can use the index to choose distinct output paths.

If the forwarded options include --controller-env, concurrency.sh also sources
that file for connection and authentication defaults. Pass only the trusted
credential file generated by the matching controller.sh run.

All submissions of one run are equivalent clients, so concurrency.sh prepares
a uniform submitter environment once: it runs `submit.sh --resolve-client` at
startup and exports the resulting executable as CAPE_SUBMIT_BIN (and
CAPE_STATUS_BIN) to every child, eliminating per-submission client
re-validation (otherwise visible as submit-wait harness overhead in the
report and Perfetto trace). Pre-set CAPE_SUBMIT_BIN/CAPE_STATUS_BIN in the
environment to override; both fall back to per-child resolution when the
submit script does not support --resolve-client.

Required scheduling options:
  --workloads N                 Total requests to submit
  --concurrency N               Maximum non-terminal requests from this run;
                                0 = open-loop (no local cap; CAPE queues)

Arrival model (gap mode, default):
  --arrival-window MIN:MAX      Delay before each submission in seconds
                                (default: 0.5:2.0)
  --arrival-distribution MODE   uniform|poisson (default: uniform)
  --seed N                      Optional reproducible random seed

Arrival model (schedule mode):
  --arrival-schedule SPEC       Pre-generate every request's absolute arrival
                                offset from a common time-zero (t0), then
                                submit at t0+offset[k]. SPEC is one of:
                                  uniform:HORIZON  offsets ~ U[0,HORIZON] s,
                                                   sorted ascending
                                  poisson:RATE     Poisson process; exponential
                                                   inter-arrivals with RATE
                                                   arrivals/second, summed
                                Overrides gap mode. Honoring a schedule needs
                                --concurrency 0; with a cap the realized submit
                                time may slip past the scheduled offset (the
                                slip is recorded, not hidden). --seed applies.
  --submitter-cap N             Maximum concurrent submit.sh workers for an
                                open-loop arrival schedule (default: 16).
                                Reaching the cap applies bounded back-pressure;
                                no request is dropped or spawned without bound.
  --schedule-skew-threshold-ratio R
                                Degrade a scheduled run when submit-skew p95
                                exceeds R times its requested mean inter-arrival
                                (default: 0.5; minimum tolerance 0.05 seconds).

Workload classes (heterogeneous mix):
  --class NAME:WEIGHT:ARGS...   Repeatable named class of extra submit.sh
                                options appended after the shared options
                                (last-one-wins), e.g.
                                --class 'bwrap:2:--isolation-policy host-stateless'
                                ARGS are whitespace-split; values must not
                                contain spaces (use --mix-file for that).
  --mix-file FILE               JSONL classes; each line
                                {"name": .., "weight": N, "args": [..],
                                 "command": [..]?}. "command" replaces the
                                shared trailing command for that class.
  --mix-order MODE              round-robin|random weighted assignment of
                                classes to workload indexes
                                (default: round-robin; random uses --seed)

Measurement report:
  --report FILE                 Generate a throughput/latency report (text to
                                FILE, JSON to FILE.json, run metadata to
                                FILE.meta.json, Perfetto timeline to
                                FILE.trace.json). Enables utilization snapshots
                                at run start/end and per-request work-marker
                                collection from request logs (both tolerate
                                controllers/CLIs without those surfaces).
                                Open the trace at https://ui.perfetto.dev: one
                                track group per GPU UUID, one row per request
                                served on that GPU. Complete calibrated markers
                                draw queuing plus processing:cpu,
                                processing:gpu, and positive-duration
                                processing:finish slices; CPU overlap is
                                benign CPU co-location, while GPU overlap is
                                real GPU co-location contention. Generic
                                two-marker workloads retain one processing
                                slice; marker-less fallback retains one
                                submit->terminal slice.
  --processing-constant S       Optional calibrated actual-processing time
                                (measure it by running calibrated_workload.sh
                                directly in the workload's execution
                                environment; median of a few runs). Marker
                                durations are always measured directly; the
                                constant serves two opt-in roles:
                                1) requests WITHOUT markers estimate
                                   queuing = elapsed - arrival - S
                                   (without S they report elapsed only), and
                                2) measured processing times are cross-checked
                                   against S and deviations are flagged as
                                   anomalies (skipped when S is unset).

Monitoring and evidence:
  --poll-interval SECONDS       Status polling period (default: 1)
  --timeout SECONDS             Whole-run timeout; 0 means unlimited
                                (default: 3600)
  --status-failure-limit N      Consecutive query failures before aborting
                                (default: 5)
  --status-token TOKEN          Override the token used by status.sh
  --ledger FILE                 Append submission/state/terminal CSV events
  --label-prefix TEXT           Injected request label prefix
                                (default: workload)

Mimic isolation:
  --work-root DIR               Base for per-request mimic directories

When more than one mimic request is submitted, each request receives
DIR/workload-NNNNNN as its --user-root so result files cannot overwrite each
other. Without --work-root, CAPE_CONCURRENCY_BUNDLE or the forwarded
--user-root is used. This path must be resolvable by the GPU node. The
controller's filesystem is never inherited.

Environment equivalents use the CAPE_CONCURRENCY_ prefix, including:
  CAPE_CONCURRENCY_WORKLOADS
  CAPE_CONCURRENCY_LIMIT
  CAPE_CONCURRENCY_ARRIVAL_WINDOW
  CAPE_CONCURRENCY_ARRIVAL_DISTRIBUTION
  CAPE_CONCURRENCY_SUBMITTER_CAP
  CAPE_CONCURRENCY_SCHEDULE_SKEW_THRESHOLD_RATIO
  CAPE_CONCURRENCY_POLL_INTERVAL
  CAPE_CONCURRENCY_TIMEOUT
  CAPE_CONCURRENCY_LEDGER
  CAPE_CONCURRENCY_BUNDLE
  CAPE_CONCURRENCY_SUBMIT_SCRIPT
  CAPE_CONCURRENCY_STATUS_SCRIPT

The cap counts QUEUED, LEASED, STARTING, RUNNING, and all other non-terminal
states, not concurrent submit.sh processes. The script waits until every
request is terminal and exits nonzero if any request fails or cannot be fully
tracked. It never cancels requests on timeout or interruption.

In gap mode and closed-loop mode, submission remains synchronous. In open-loop
schedule mode, the parent launches bounded submit.sh workers at the absolute
offsets, then captures and validates every result in index order. A slow worker
therefore does not delay the next arrival unless the explicit submitter cap is
full. Uniform gap mode draws directly from MIN:MAX and poisson uses an
exponential inter-arrival delay clipped to that same window; setting MIN equal
to MAX gives a fixed gap. In schedule mode the full offset list is drawn up
front (reproducible with --seed) and each request's ledger rows carry both its
scheduled offset and its actual submit offset from t0.

The ledger (v3) appends measurement columns after the original ones:
label, class, scheduled_offset, submit_offset, node_id, isolation_policy,
runtime_adapter, gpu_uuids, work_start, work_end, cpu_done, gpu_done,
created_at, leased_at, started_at.
Placement fields are read from the request status JSON; work markers are read
from request logs when --report is active and the workload printed
CAPE_CALIBRATED markers (see calibrated_workload.sh).

The workload's GPU mode is detected from its own gpu_launch marker, not
configured here, because this script never invokes the workload directly. A
work-bound workload (calibrated_workload.sh --gpu-mode vecadd, the default) has
no constant processing time: its duration is what the available bandwidth
produced. For such a run any --processing-constant is reported as IGNORED, the
no-marker fallback decomposition is disabled, and the calibration cross-check is
skipped -- otherwise real contention would be reported as measurement error.

Each request uses a unique session key, so warm reuse is disabled and these
are cold-path measurements. The report preserves legacy queuing_time
(submit -> work_start) and additionally decomposes it into client submit
overhead (submit -> created_at), true controller queueing
(created_at -> leased_at), session assembly (leased_at -> started_at), and
agent handoff (started_at -> work_start). It reports actual processing
(work_end - work_start when markers exist; otherwise the constant), and
additionally reports cpu_time (work_start -> cpu_done) and gpu_time
(cpu_done -> gpu_done) for complete marker sets. It computes overall and
steady-state throughput plus per-class/per-policy/per-node breakdowns.
EOF
}


# Split the shared submit arguments once into options and trailing command.
declare -a base_submit_opts=()
declare -a base_submit_cmd=()
base_has_command=0
for argument in ${submit_args[@]+"${submit_args[@]}"}; do
  if [ "$base_has_command" = 0 ] && [ "$argument" = -- ]; then
    base_has_command=1
    continue
  fi
  if [ "$base_has_command" = 1 ]; then
    base_submit_cmd+=("$argument")
  else
    base_submit_opts+=("$argument")
  fi
done

build_effective_submit_args() {
  local index="$1"
  local padded="$2"
  local class="$3"
  local request_label="$4"
  local -a injected=(
    --label "$request_label"
    --env "CAPE_CONCURRENCY_INDEX=$index"
    --env "CAPE_CONCURRENCY_TOTAL=$workloads"
    --env "CAPE_CONCURRENCY_RUN_ID=$run_id"
  )
  local request_is_mimic="$submit_is_mimic"
  local session_id_supplied=0
  local option
  local -a class_extra=()
  local -a effective_cmd=(${base_submit_cmd[@]+"${base_submit_cmd[@]}"})
  local effective_has_command="$base_has_command"
  if [ -n "$class" ]; then
    injected+=(--env "CAPE_CONCURRENCY_CLASS=$class")
    [ "${class_is_mimic[$class]}" != 1 ] || request_is_mimic=1
    [ -z "${class_args_blob[$class]}" ] || \
      mapfile -t class_extra <<< "${class_args_blob[$class]}"
    if [ -n "${class_cmd_blob[$class]}" ]; then
      mapfile -t effective_cmd <<< "${class_cmd_blob[$class]}"
      effective_has_command=1
    fi
  fi
  for option in \
    ${base_submit_opts[@]+"${base_submit_opts[@]}"} \
    ${class_extra[@]+"${class_extra[@]}"}; do
    case "$option" in
      --session-id|--session-id=*)
        session_id_supplied=1
        ;;
    esac
  done
  if [ "$session_id_supplied" != 1 ]; then
    injected+=(--session-id "$run_id-$padded")
  fi
  if [ "$request_is_mimic" = 1 ] && [ -n "$work_root" ]; then
    if [ -n "$class" ]; then
      injected+=(--user-root "$work_root/$class/workload-$padded")
    else
      injected+=(--user-root "$work_root/workload-$padded")
    fi
  fi

  EFFECTIVE_SUBMIT_ARGS=(
    ${base_submit_opts[@]+"${base_submit_opts[@]}"}
    ${class_extra[@]+"${class_extra[@]}"}
    "${injected[@]}"
  )
  if [ "$effective_has_command" = 1 ]; then
    EFFECTIVE_SUBMIT_ARGS+=(-- ${effective_cmd[@]+"${effective_cmd[@]}"})
  fi
}


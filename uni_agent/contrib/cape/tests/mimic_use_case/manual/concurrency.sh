# Extract CAPE_CALIBRATED work markers from a request log stream on stdin.
parse_work_markers() {
  "$JSON_PYTHON" -c '
import sys

markers = {}
gpu_mode = ""
for line in sys.stdin:
    parts = line.split()
    if len(parts) >= 3 and parts[0] == "CAPE_CALIBRATED":
        markers[parts[1]] = parts[2]
        # gpu_launch carries key=value fields; mode= tells us whether the
        # workload is wall-clock bound (constant) or work bound (contention
        # sensitive). Detected from evidence rather than configured, because
        # this script never invokes the workload itself.
        if parts[1] == "gpu_launch":
            for field in parts[2:]:
                if field.startswith("mode="):
                    gpu_mode = field[5:]
print("\x1f".join(
    list(markers.get(name, "")
         for name in ("work_start", "cpu_done", "gpu_done", "work_end"))
    + [gpu_mode, markers.get("lock_wait_start", ""), markers.get("lock_acquired", "")]
))
'
}

collect_work_markers() {
  local request_id="$1" for_class="$2"
  WORK_START=""
  CPU_DONE=""
  GPU_DONE=""
  WORK_END=""
  GPU_MODE=""
  LOCK_WAIT_START=""
  LOCK_ACQUIRED=""
  [ -n "$report_file" ] || return 0
  status_auth_args_for_class "$for_class"
  local log_text parsed
  if log_text="$("$STATUS_SCRIPT" "${status_global_args[@]}" \
      ${STATUS_AUTH_ARGS[@]+"${STATUS_AUTH_ARGS[@]}"} logs "$request_id" \
      2>/dev/null)"; then
    if parsed="$(printf '%s\n' "$log_text" | parse_work_markers)"; then
      IFS=$'\x1f' read -r WORK_START CPU_DONE GPU_DONE WORK_END GPU_MODE LOCK_WAIT_START LOCK_ACQUIRED <<< "$parsed"
    fi
  else
    log "note: no log markers available for $request_id (fallback decomposition will be used)"
  fi
}


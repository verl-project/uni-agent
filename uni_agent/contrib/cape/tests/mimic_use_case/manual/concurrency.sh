register_class() {
  local name="$1" weight="$2" args_blob="$3" cmd_blob="$4"
  [[ "$name" =~ ^[A-Za-z0-9_.-]+$ ]] || die "invalid class name: $name"
  case "$weight" in
    ''|*[!0-9]*) die "class $name: weight must be a positive integer" ;;

  request_delays["$request_id"]="${submit_index_delay[$index]}"
  request_labels["$request_id"]="${submit_index_label[$index]}"
  request_classes["$request_id"]="${submit_index_class[$index]}"
  request_scheduled["$request_id"]="${submit_index_scheduled[$index]}"
  request_submit_offsets["$request_id"]="${submit_index_offset[$index]}"
  last_states["$request_id"]=""
  status_failures["$request_id"]=0
  [ "${#active_ids[@]}" -le "$max_active" ] || max_active="${#active_ids[@]}"
  ledger_event SUBMITTED "$index" "$request_id" \
    "${submit_index_time[$index]}" "${submit_index_delay[$index]}" \
    SUBMITTED "" "${submit_index_label[$index]}" \
    "${submit_index_class[$index]}" "${submit_index_scheduled[$index]}" \
    "${submit_index_offset[$index]}"
  printf '%s\n' "$request_id"
}

flush_submitter_results() {
  local index rc request_output request_id result_dir
  while [ "${submitter_results_ready[$next_submit_result_index]:-0}" = 1 ]; do
    index="$next_submit_result_index"
    result_dir="${submitter_result_dirs[$index]}"
    rc="$(sed -n '1p' "$result_dir/exit-code")"
    [ ! -s "$result_dir/stderr" ] || cat "$result_dir/stderr" >&2
    if [ "$rc" != 0 ]; then
      submission_error=1
      submitter_failed_count=$((submitter_failed_count + 1))
      log "submission failed for workload $index (exit $rc)"
    else
      request_output="$(cat "$result_dir/stdout")"
      request_id="${request_output//$'\r'/}"
      if [[ "$request_id" =~ ^req-[A-Za-z0-9._-]+$ ]] && \
         [ "$(printf '%s\n' "$request_id" | wc -l)" -eq 1 ]; then
        register_submission "$index" "$request_id"
      else
        submission_error=1
        submitter_failed_count=$((submitter_failed_count + 1))
        log "submit.sh returned an invalid request id for workload $index: $request_output"
      fi
    fi
    unset 'submitter_results_ready[$index]'
    next_submit_result_index=$((next_submit_result_index + 1))
  done
}

harvest_submitters() {
  local wait_for_one="${1:-0}" found index pid result_dir
  while true; do
    found=0
    for index in "${!submitter_pids[@]}"; do
      result_dir="${submitter_result_dirs[$index]}"
      [ -f "$result_dir/exit-code" ] || continue
      pid="${submitter_pids[$index]}"
      wait "$pid" 2>/dev/null || true
      unset 'submitter_pids[$index]'
      active_submitters=$((active_submitters - 1))
      submitter_completed_count=$((submitter_completed_count + 1))
      submitter_results_ready["$index"]=1
      found=1
    done
    flush_submitter_results
    [ "$wait_for_one" != 1 ] || [ "$found" = 1 ] && return 0
    [ "$wait_for_one" = 1 ] || return 0
    within_timeout || return 1
    sleep 0.005
  done
}

launch_submitter() {
  local index="$1" run_tag="$2" padded result_dir
  padded="$(printf '%06d' "$index")"
  result_dir="$submit_result_root/$padded"
  mkdir -p "$result_dir"
  submitter_result_dirs["$index"]="$result_dir"
  (
    set +e
    CAPE_SUBMIT_RUN_TAG="$run_tag" \
    CAPE_SUBMIT_TIMING_FILE="$result_dir/timing.env" \
      "$SUBMIT_SCRIPT" "${EFFECTIVE_SUBMIT_ARGS[@]}" \
      > "$result_dir/stdout" 2> "$result_dir/stderr"
    rc=$?
    printf '%s\n' "$rc" > "$result_dir/exit-code.tmp"
    mv -- "$result_dir/exit-code.tmp" "$result_dir/exit-code"
    exit 0
  ) &
  submitter_pids["$index"]=$!
  dispatched_count=$((dispatched_count + 1))
  active_submitters=$((active_submitters + 1))
  [ "$active_submitters" -le "$peak_submitters" ] || \
    peak_submitters="$active_submitters"
}

within_timeout() {
  [ "$run_timeout" = 0 ] && return 0
  local now
  now="$(date +%s)"
  [ $((now - start_epoch)) -lt "$run_timeout" ]
}

sleep_before_arrival() {
  local delay="$1"
  if ! awk -v value="$delay" 'BEGIN {exit !(value > 0)}'; then
    return 0
  fi
  if [ "$run_timeout" = 0 ]; then
    sleep "$delay"
    return 0
  fi

  local now elapsed remaining
  now="$(date +%s)"
  elapsed=$((now - start_epoch))
  remaining=$((run_timeout - elapsed))
  [ "$remaining" -gt 0 ] || return 1
  if awk -v delay="$delay" -v remaining="$remaining" \
    'BEGIN {exit !(delay >= remaining)}'; then
    sleep "$remaining"
    return 1
  fi
  sleep "$delay"
}

poll_active() {
  local -a remaining=()
  local request_id status_json parsed state exit_code failures index delay now
  local node_id isolation_policy runtime_adapter gpu_uuids
  local created_at leased_at started_at
  local req_label req_class req_sched req_submit_offset
  local sweep_start sweep_end sweep_elapsed
  sweep_start="$(date +%s.%N)"
  for request_id in "${active_ids[@]}"; do
    req_class="${request_classes[$request_id]:-}"
    status_auth_args_for_class "$req_class"
    if status_json="$("$STATUS_SCRIPT" "${status_global_args[@]}" \
        ${STATUS_AUTH_ARGS[@]+"${STATUS_AUTH_ARGS[@]}"} status "$request_id")"; then
      if parsed="$(parse_status_payload "$status_json")"; then
        status_failures["$request_id"]=0
      else
        parsed=""
      fi
    else
      parsed=""
    fi

    if [ -z "$parsed" ]; then
      failures=$(( ${status_failures[$request_id]:-0} + 1 ))
      status_failures["$request_id"]="$failures"
      log "status query failed for $request_id ($failures/$status_failure_limit)"
      remaining+=("$request_id")
      if [ "$failures" -ge "$status_failure_limit" ]; then
        fatal_status_error=1
      fi
      continue
    fi

    IFS=$'\t' read -r state exit_code node_id isolation_policy runtime_adapter \
      gpu_uuids created_at leased_at started_at <<< "$parsed"
    index="${request_indexes[$request_id]}"
    delay="${request_delays[$request_id]}"
    req_label="${request_labels[$request_id]:-}"
    req_sched="${request_scheduled[$request_id]:-}"
    req_submit_offset="${request_submit_offsets[$request_id]:-}"
    if [ "${last_states[$request_id]:-}" != "$state" ]; then
      last_states["$request_id"]="$state"
      now="$(date +%s.%N)"
      log "request=$request_id index=$index state=$state"
      ledger_event STATE "$index" "$request_id" "$now" "$delay" "$state" \
        "$exit_code" "$req_label" "$req_class" "$req_sched" \
        "$req_submit_offset" "$node_id" "$isolation_policy" \
        "$runtime_adapter" "$gpu_uuids" "" "" "" "" \
        "$created_at" "$leased_at" "$started_at"
    fi

    case "$state" in
      COMPLETED|FAILED|CANCELLED|EXPIRED|LOST|INFEASIBLE)
        terminal_count=$((terminal_count + 1))
        collect_work_markers "$request_id" "$req_class"
        now="$(date +%s.%N)"
        ledger_event TERMINAL "$index" "$request_id" "$now" "$delay" "$state" \
          "$exit_code" "$req_label" "$req_class" "$req_sched" \
          "$req_submit_offset" "$node_id" "$isolation_policy" \
          "$runtime_adapter" "$gpu_uuids" "$WORK_START" "$WORK_END" \
          "$CPU_DONE" "$GPU_DONE" "$created_at" "$leased_at" \
          "$started_at" "$GPU_MODE" "$LOCK_WAIT_START" "$LOCK_ACQUIRED"
        if [ "$state" = COMPLETED ] && [ "$exit_code" = 0 ]; then
          succeeded_count=$((succeeded_count + 1))
        else
          failed_count=$((failed_count + 1))
        fi
        ;;
      *)
        remaining+=("$request_id")
        ;;
    esac
  done
  active_ids=(${remaining[@]+"${remaining[@]}"})
  [ "${#active_ids[@]}" -le "$max_active" ] || max_active="${#active_ids[@]}"
  sweep_end="$(date +%s.%N)"
  sweep_elapsed="$(awk -v a="$sweep_start" -v b="$sweep_end" \
    'BEGIN {printf "%.3f", b - a}')"
  sweep_count=$((sweep_count + 1))
  sweep_total="$(awk -v total="$sweep_total" -v value="$sweep_elapsed" \
    'BEGIN {printf "%.3f", total + value}')"
  if awk -v value="$sweep_elapsed" -v peak="$sweep_max" \
    'BEGIN {exit !(value > peak)}'; then
    sweep_max="$sweep_elapsed"
  fi
}

report_active_requests() {
  if [ "${#active_ids[@]}" -gt 0 ]; then
    log "requests still active: ${active_ids[*]}"
  fi
}

handle_interrupt() {
  trap - INT TERM
  log "interrupted; submitted requests are not being cancelled"
  local index
  for index in "${!submitter_pids[@]}"; do
    kill -TERM "${submitter_pids[$index]}" 2>/dev/null || true
  done
  for index in "${!submitter_pids[@]}"; do
    wait "${submitter_pids[$index]}" 2>/dev/null || true
  done
  report_active_requests
  if [ "$temporary_submit_result_root" = 1 ]; then
    rm -rf "$submit_result_root"
  fi
  exit 130
}

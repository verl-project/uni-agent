  [ -z "${class_weight[$name]:-}" ] || die "duplicate class name: $name"
  class_names+=("$name")
  class_weight["$name"]="$weight"
  class_args_blob["$name"]="$args_blob"
  class_cmd_blob["$name"]="$cmd_blob"
  class_is_mimic["$name"]=0

  local -a class_arguments=()
  [ -z "$args_blob" ] || mapfile -t class_arguments <<< "$args_blob"
  local i=0 argument
  while [ "$i" -lt "${#class_arguments[@]}" ]; do
    argument="${class_arguments[$i]}"
    case "$argument" in
      --controller-env|--controller-env=*)
        die "class $name: --controller-env is not allowed at class level" ;;
      --user)
        i=$((i + 1))
        [ "$i" -lt "${#class_arguments[@]}" ] || die "class $name: --user needs a value"
        class_user["$name"]="${class_arguments[$i]}"
        ;;
      --user=*) class_user["$name"]="${argument#*=}" ;;
      --token)
        i=$((i + 1))
        [ "$i" -lt "${#class_arguments[@]}" ] || die "class $name: --token needs a value"
        class_token["$name"]="${class_arguments[$i]}"
        ;;
      --token=*) class_token["$name"]="${argument#*=}" ;;
      --token-file)
        i=$((i + 1))
        [ "$i" -lt "${#class_arguments[@]}" ] || die "class --token-file needs a path"
        class_token_file["$name"]="${class_arguments[$i]}"
        class_token["$name"]="$(cape_read_secret "${class_arguments[$i]}")" || exit 2
        ;;
      --token-file=*) class_token_file["$name"]="${argument#*=}"; class_token["$name"]="$(cape_read_secret "${argument#*=}")" || exit 2 ;;
      --mimic|--mimic=*) class_is_mimic["$name"]=1 ;;
    esac
    i=$((i + 1))
  done
}

